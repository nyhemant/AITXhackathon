/** Rough equirectangular project for lower 48 → viewBox */
window.fpProjectUS = function fpProjectUS(lat, lon, width, height) {
  const padX = 36;
  const padY = 48;
  const lon0 = -124.8;
  const lon1 = -66.9;
  const lat0 = 24.5;
  const lat1 = 49.4;
  const x = padX + ((lon - lon0) / (lon1 - lon0)) * (width - padX * 2);
  const y = padY + ((lat1 - lat) / (lat1 - lat0)) * (height - padY * 2 - 20);
  return { x, y };
};
