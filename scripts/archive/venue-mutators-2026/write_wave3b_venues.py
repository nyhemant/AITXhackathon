def bans_except(keep: set[str], extra: list[tuple[str, str]] | None = None) -> list[dict]:
    reasons = {
        "african-elephant": "Not confirmed as African elephant on the official public list.",
        "african-lion": "Not confirmed as African lion on the official public list.",
        "sumatran-tiger": "Official tiger (if any) is not Sumatran.",
        "african-penguin": "Official penguins (if any) are not African.",
        "western-lowland-gorilla": "Not on the official public list reviewed.",
        "chimpanzee": "Not on the official public list reviewed.",
        "reticulated-giraffe": "Not on the official public list reviewed.",
        "zebra": "Not on the official public list reviewed.",
        "red-panda": "Not on the official public list reviewed.",
        "asian-small-clawed-otter": "Official otter (if any) is a different species.",
        "nile-hippo": "Official hippo (if any) is not Nile / common hippo.",
        "galapagos-tortoise": "Official tortoise (if any) is not Galápagos.",
        "orangutan": "Not on the official public list reviewed.",
        "cheetah": "Not on the official public list reviewed.",
        "koala": "Not on the official public list reviewed.",
        "giant-panda": "Not on the official public list reviewed.",
        "caribbean-flamingo": "Official flamingo (if any) is not Caribbean/American.",
        "two-toed-sloth": "Not on the official public list reviewed.",
        "shark": "Aquarium-side or not named on the official zoo list.",
        "cm-outdoor": "Neither-kind leftover; zoo kits list zoo|both cards only.",
    }
    out = [ban(cid, reasons[cid]) for cid in CLONE_BANS if cid not in keep]
    for cid, reason in extra or []:
        if cid not in {row["catalog_id"] for row in out}:
            out.append(ban(cid, reason))
    return out


